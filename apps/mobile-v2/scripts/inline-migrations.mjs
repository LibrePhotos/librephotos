/**
 * Inline the drizzle-kit generated SQL migrations into a committed TS module
 * (src/db/migrations-sql.ts) as an ordered list of executable statements.
 *
 * Why: the app bundler (Metro) and jest (babel) can't read `.sql` via `fs`, and
 * we don't want @types/node in the app tsconfig. This module is the single
 * source used by the Node test harness AND the wipe-and-reseed schema rebuild.
 *
 * Run after `drizzle-kit generate`:  node scripts/inline-migrations.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, "..", "src", "db", "migrations");
const journal = JSON.parse(readFileSync(join(migrationsDir, "meta", "_journal.json"), "utf8"));

/** @type {string[]} */
const statements = [];
for (const entry of journal.entries.sort((a, b) => a.idx - b.idx)) {
  const sqlPath = join(migrationsDir, `${entry.tag}.sql`);
  const raw = readFileSync(sqlPath, "utf8");
  for (const chunk of raw.split("--> statement-breakpoint")) {
    const stmt = chunk.trim();
    if (stmt) statements.push(stmt);
  }
}

const body = `/**
 * AUTO-GENERATED by scripts/inline-migrations.mjs — do not edit by hand.
 * Ordered, executable SQL statements for the committed drizzle migrations.
 * Regenerate after every \`drizzle-kit generate\`.
 */
export const MIGRATION_STATEMENTS: string[] = [
${statements.map((s) => "  " + JSON.stringify(s) + ",").join("\n")}
];
`;

writeFileSync(join(migrationsDir, "..", "migrations-sql.ts"), body, "utf8");
console.log(`Wrote src/db/migrations-sql.ts (${statements.length} statements).`);
