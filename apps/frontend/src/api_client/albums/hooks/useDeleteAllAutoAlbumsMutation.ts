import { endpoints } from "@librephotos/api-client";
import { useMutation } from "@tanstack/react-query";
import i18n from "../../../i18n";
import { notification } from "../../../service/notifications";
import { apiClient, ApiError, queryClient } from "../../api";
import { photoGridKeys } from "../../photos/keys";
import { albumKeys } from "../keys";

export const useDeleteAllAutoAlbumsMutation = () =>
  useMutation({
    mutationFn: async () => {
      await endpoints.deleteAllAutoAlbums(apiClient);
    },
    onSuccess: () => {
      notification.deleteAutogeneratedAlbums();
      queryClient.invalidateQueries({ queryKey: albumKeys.autoAlbums() });
      queryClient.invalidateQueries({ queryKey: photoGridKeys.kind("autoAlbum") });
    },
    onError: error => {
      // The fetch client already reports a 401 and a 500; anything else (a 403,
      // no connection) used to fail without a word.
      if (error instanceof ApiError && (error.status === 401 || error.status === 500)) {
        return;
      }
      notification.requestFailed(
        i18n.t("toasts.deleteallautoalbumsfailedtitle"),
        (error instanceof ApiError && error.serverMessage) || i18n.t("toasts.deleteallautoalbumsfailed")
      );
    },
  });
