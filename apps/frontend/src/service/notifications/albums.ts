import i18n from "../../i18n";
import { toast } from "./toast";

function setCoverPhoto() {
  toast.success(i18n.t("toasts.setcoverphoto"), { title: i18n.t("toasts.setcoverphototitle") });
}

// One short sentence with no title: "Added 2 photos to Lisbon". `numberOfPhotos` is passed beside
// `count` for the translations that still read "{{numberOfPhotos}} photo(s)".

function addPhotosToAlbum(title: string, count: number) {
  toast.success(i18n.t("toasts.addtoalbum", { title, count, numberOfPhotos: count }));
}

function removePhotosFromAlbum(title: string, count: number) {
  toast.success(i18n.t("toasts.removefromalbum", { title, count, numberOfPhotos: count }));
}

function createAlbum(title: string, count: number) {
  toast.success(i18n.t("toasts.createnewalbum", { title, count, numberOfPhotos: count }));
}

function renameAlbum(oldTitle: string, newTitle: string) {
  // The placeholder names every translation uses; passing others left the
  // literal {{albumTitle}} in the toast.
  toast.success(i18n.t("toasts.renamealbum", { albumTitle: oldTitle, newAlbumTitle: newTitle }), {
    title: i18n.t("toasts.renamealbumtitle"),
  });
}

function createAlbumCollection(name: string) {
  toast.success(i18n.t("toasts.createalbumcollection", { name }), { title: i18n.t("toasts.albumcollectiontitle") });
}

function renameAlbumCollection(oldName: string, newName: string) {
  toast.success(i18n.t("toasts.renamealbumcollection", { oldName, newName }), {
    title: i18n.t("toasts.albumcollectiontitle"),
  });
}

function deleteAlbumCollection(name: string) {
  toast.success(i18n.t("toasts.deletealbumcollection", { name }), { title: i18n.t("toasts.albumcollectiontitle") });
}

function deleteAlbum(albumTitle: string) {
  toast.success(i18n.t("toasts.deletealbum", { albumTitle }), { title: i18n.t("toasts.deletealbumtitle") });
}

function leaveAlbum(albumTitle: string) {
  toast.success(i18n.t("toasts.leavealbum", { albumTitle }), { title: i18n.t("toasts.leavealbumtitle") });
}

function deleteAutogeneratedAlbums() {
  toast.success(i18n.t("toasts.deleteallautoalbums"), { title: i18n.t("toasts.deleteallautoalbumstitle") });
}

function generateEventAlbums() {
  toast.success(i18n.t("toasts.generateeventalbums"), { title: i18n.t("toasts.generateeventalbumstitle") });
}

function regenerateEventAlbums() {
  toast.success(i18n.t("toasts.regenerateevents"), { title: i18n.t("toasts.regenerateeventstitle") });
}

function toggleAlbumSharing(share: boolean) {
  toast.success(i18n.t(share ? "toasts.sharingalbum" : "toasts.unsharingalbum"), {
    title: i18n.t(share ? "toasts.sharingalbumtitle" : "toasts.unsharingalbumtitle"),
  });
}

function saveUserPlace(name: string, count: number) {
  toast.success(i18n.t("toasts.saveuserplace", { name, count }), {
    title: i18n.t("toasts.saveuserplacetitle", { name }),
  });
}

function deleteUserPlace(name: string) {
  toast.success(i18n.t("toasts.deleteuserplace", { name }), { title: i18n.t("toasts.deleteuserplacetitle") });
}

export const albums = {
  addPhotosToAlbum,
  createAlbum,
  createAlbumCollection,
  deleteAlbum,
  deleteAlbumCollection,
  deleteAutogeneratedAlbums,
  deleteUserPlace,
  generateEventAlbums,
  leaveAlbum,
  regenerateEventAlbums,
  removePhotosFromAlbum,
  renameAlbum,
  renameAlbumCollection,
  saveUserPlace,
  setCoverPhoto,
  toggleAlbumSharing,
};
