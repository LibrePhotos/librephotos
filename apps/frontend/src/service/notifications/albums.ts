import i18n from "../../i18n";
import { toast } from "./toast";

function setCoverPhoto() {
  toast.success(i18n.t("toasts.setcoverphoto"), { title: i18n.t("toasts.setcoverphototitle") });
}

function addPhotosToAlbum(title: string, numberOfPhotos: number) {
  toast.success(i18n.t("toasts.addtoalbum", { title, numberOfPhotos }), { title: i18n.t("toasts.addtoalbumtitle") });
}

function removePhotosFromAlbum(title: string, numberOfPhotos: number) {
  toast.success(i18n.t("toasts.removefromalbum", { title, numberOfPhotos }), {
    title: i18n.t("toasts.removefromalbumtitle"),
  });
}

function createAlbum(title: string, numberOfPhotos: number) {
  toast.success(i18n.t("toasts.createnewalbum", { title, numberOfPhotos }), {
    title: i18n.t("toasts.createalbumtitle"),
  });
}

function renameAlbum(oldTitle: string, newTitle: string) {
  // The placeholder names every translation uses; passing others left the
  // literal {{albumTitle}} in the toast.
  toast.success(i18n.t("toasts.renamealbum", { albumTitle: oldTitle, newAlbumTitle: newTitle }), {
    title: i18n.t("toasts.renamealbumtitle"),
  });
}

function deleteAlbum(albumTitle: string) {
  toast.success(i18n.t("toasts.deletealbum", { albumTitle }), { title: i18n.t("toasts.deletealbumtitle") });
}

function deleteAutogeneratedAlbums() {
  toast.success(i18n.t("toasts.deleteallautoalbums"), { title: i18n.t("toasts.deleteallautoalbumstitle") });
}

function generateEventAlbums() {
  toast.success(i18n.t("toasts.generateeventalbums"), { title: i18n.t("toasts.generateeventalbumstitle") });
}

function regenerateEventAlbums() {
  toast.success(i18n.t("toasts.regenerateevents"), { title: i18n.t("toasts.regenerateeventstitle") });
}

function toggleAlbumSharing(share: boolean) {
  toast.success(i18n.t(share ? "toasts.sharingalbum" : "toasts.unsharingalbum"), {
    title: i18n.t(share ? "toasts.sharingalbumtitle" : "toasts.unsharingalbumtitle"),
  });
}

export const albums = {
  addPhotosToAlbum,
  createAlbum,
  deleteAlbum,
  deleteAutogeneratedAlbums,
  generateEventAlbums,
  regenerateEventAlbums,
  removePhotosFromAlbum,
  renameAlbum,
  setCoverPhoto,
  toggleAlbumSharing,
};
