#!/usr/bin/env python3
"""Generate apps/backend/openapi.json, the committed OpenAPI schema of the API.

drf-spectacular builds the schema from the DRF views and serializers.
packages/api-client compares its zod schemas with the components in this file
(src/__tests__/openapi.contract.test.ts), so a serializer change has to reach
the file in the same pull request. test-backend.yml runs ``--check``, which
fails when the committed file is not what the code generates.

The schema is always generated under ``librephotos.settings.test_sqlite`` (the
DEBUG routes it mounts, ``/api/schema`` and friends, are part of the file), so
the result does not depend on the shell's settings module. SECRET_KEY,
BASE_DATA and BASE_LOGS default to throwaway values; the schema reads none of
them.

drf-spectacular reports what it cannot describe (an APIView without a
serializer, an untyped path parameter). openapi-baseline.txt lists the reports
that predate this script, one per line. It only shrinks: a new report fails the
run (declare the response with a serializer or ``@extend_schema``), and a
listed one that is gone fails it too until ``--update-baseline`` drops it.
Issue #485 tracks the rest.

Usage (from apps/backend):
  python scripts/openapi_schema.py                    regenerate openapi.json
  python scripts/openapi_schema.py --check            fail if openapi.json is stale
  python scripts/openapi_schema.py --update-baseline  regenerate, drop fixed reports
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "openapi.json"
BASELINE = ROOT / "openapi-baseline.txt"
SETTINGS = "librephotos.settings.test_sqlite"
HEADER = (
    "# drf-spectacular's reports for the committed schema, generated by",
    "# scripts/openapi_schema.py. Do not edit by hand. The file only shrinks: fix",
    "# the view or serializer (a serializer_class or @extend_schema(responses=...)),",
    "# then run `python scripts/openapi_schema.py --update-baseline`. Issue #485.",
)
# "<source file>: Error [AlbumView]: message" -> "Error [AlbumView]: message".
# The source location is an absolute path, so it differs between machines.
REPORT = re.compile(r"^(?:.*?: )?((?:Warning|Error)(?: \[[^\]]*\])?: .*)$", re.DOTALL)


def _configure_django() -> None:
    os.environ["DJANGO_SETTINGS_MODULE"] = SETTINGS
    scratch = tempfile.mkdtemp(prefix="librephotos-openapi-")
    os.environ.setdefault("SECRET_KEY", "openapi-schema")
    os.environ.setdefault("BASE_DATA", scratch)
    os.environ.setdefault("BASE_LOGS", os.path.join(scratch, "logs"))
    sys.path.insert(0, str(ROOT))
    import django

    django.setup()


def _report_text(key: str) -> str:
    match = REPORT.match(key)
    return " ".join((match.group(1) if match else key).split())


def generate() -> tuple[str, set[str]]:
    """The schema as JSON text, and drf-spectacular's reports while building it."""
    _configure_django()
    from drf_spectacular.drainage import GENERATOR_STATS
    from drf_spectacular.settings import spectacular_settings
    from drf_spectacular.validation import validate_schema
    from rest_framework.utils.encoders import JSONEncoder

    GENERATOR_STATS.reset()
    generator = spectacular_settings.DEFAULT_GENERATOR_CLASS()
    with GENERATOR_STATS.silence():
        schema = generator.get_schema(request=None, public=True)
    validate_schema(schema)
    reports = {
        _report_text(key)
        for key in (*GENERATOR_STATS._warn_cache, *GENERATOR_STATS._error_cache)
    }
    text = json.dumps(schema, cls=JSONEncoder, indent=2, ensure_ascii=False) + "\n"
    return text, reports


def read_baseline() -> set[str]:
    if not BASELINE.exists():
        return set()
    lines = BASELINE.read_text(encoding="utf-8").splitlines()
    return {line for line in lines if line and not line.startswith("#")}


def write_baseline(reports: set[str]) -> None:
    body = "\n".join((*HEADER, *sorted(reports)))
    BASELINE.write_text(body + "\n", encoding="utf-8", newline="\n")


def compare_reports(reports: set[str], baseline: set[str], update: bool) -> bool:
    """Print new and fixed reports; True when the baseline is in step."""
    new = sorted(reports - baseline)
    fixed = sorted(baseline - reports)
    for report in new:
        print(f"new schema report (not in {BASELINE.name}): {report}")
    if new:
        print(
            "Declare the view's response (a serializer, or @extend_schema(responses=...))"
            " or type the path parameter; the baseline only shrinks."
        )
    if fixed and update and not new:
        write_baseline(baseline & reports)
        print(f"Dropped {len(fixed)} fixed report(s) from {BASELINE.name}.")
        return True
    for report in fixed:
        print(f"fixed schema report still in {BASELINE.name}: {report}")
    if fixed:
        print("Run `python scripts/openapi_schema.py --update-baseline` and commit it.")
    return not new and not fixed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--check", action="store_true", help="fail if openapi.json is stale"
    )
    mode.add_argument(
        "--update-baseline",
        action="store_true",
        help="drop fixed reports from openapi-baseline.txt (never adds any)",
    )
    args = parser.parse_args(argv)

    text, reports = generate()
    ok = compare_reports(reports, read_baseline(), update=args.update_baseline)
    current = SCHEMA.read_text(encoding="utf-8") if SCHEMA.exists() else ""
    if args.check:
        if current != text:
            print(
                f"{SCHEMA.name} is stale: the views or serializers changed without it."
                " Run `python scripts/openapi_schema.py` and commit the result."
            )
            return 1
    elif current != text:
        SCHEMA.write_text(text, encoding="utf-8", newline="\n")
        print(f"Wrote {SCHEMA.name}.")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
