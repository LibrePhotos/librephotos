#!/usr/bin/env python3
"""Ruff baseline for the backend: per-file exceptions for findings that predate a rule.

Every rule selected in pyproject.toml applies to new code at once. The findings
that existed when a rule was turned on are listed in ruff-baseline.toml, one
`"path" = [codes]` entry per file, which pyproject.toml pulls in with
`extend = "ruff-baseline.toml"`. `ruff check` (CI, editors, pre-commit) then
passes the listed file/code pairs and fails on any other.

This script generates that file and keeps it honest:

  - it runs ruff with the baseline switched off (`lint.per-file-ignores = {}`;
    the permanent `extend-per-file-ignores` in pyproject.toml still apply) and
    renders the findings as the baseline, sorted by path and code;
  - the check fails when the result differs from the committed file: a file/code
    pair that is not listed is a new finding (fix it), and a listed pair that no
    longer occurs is stale (run --update and commit the smaller file), because a
    stale entry would let the rule come back in that file unnoticed;
  - with --base-ref, the committed baseline must not list a file/code pair that
    the baseline at that ref did not list (renamed files keep their old entry),
    unless the change also touches the ruff config in pyproject.toml (a new
    rule or a ruff upgrade legitimately adds entries; they are printed for
    review). So running --update to absorb a new finding still fails CI;
  - syntax errors, or ruff failing, exit 2.

The baseline is per file and code, not per finding: a file listed for BLE001
may gain another blind `except` without failing. That is the price of using
ruff's own config, which keeps editors and pre-commit in step with CI.

Standard library only and no tomllib, so it runs on Python 3.10 (the floor).

Usage (from apps/backend):
  python scripts/ruff_baseline.py                 check against the baseline
  python scripts/ruff_baseline.py --update        rewrite the baseline
  python scripts/ruff_baseline.py --check --base-ref origin/dev
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "ruff-baseline.toml"
PYPROJECT = ROOT / "pyproject.toml"
REPO_PREFIX = "apps/backend/"
TABLE = "[lint.per-file-ignores]"
HEADER = [
    "# Ruff baseline: rule findings that predate the rule, per file. Generated by",
    "# scripts/ruff_baseline.py and pulled in by `extend` in pyproject.toml.",
    "# Do not edit by hand. The file only shrinks: fix the code, then run",
    "# `python scripts/ruff_baseline.py --update`; never run it to accept new findings.",
    "# Permanent exceptions belong in [tool.ruff.lint.extend-per-file-ignores].",
]
ENTRY = re.compile(r'^"((?:[^"\\]|\\.)*)" = \[(.*)\]$')
CODE = re.compile(r"^[A-Z]+[0-9]+$")
GLOB_CHARS = set("*?[]{}!")
SYNTAX_ERROR = "invalid-syntax"

Baseline = dict[str, set[str]]


@dataclass(frozen=True)
class Finding:
    path: str
    code: str
    row: int
    column: int
    message: str

    def describe(self) -> str:
        return f"{self.path}:{self.row}:{self.column}: {self.code} {self.message}"


class RuffError(Exception):
    """Ruff did not produce a usable result."""


def _relative(filename: str) -> str:
    path = Path(filename)
    try:
        path = path.resolve().relative_to(ROOT)
    except ValueError:
        pass
    return path.as_posix()


def _int_field(record: dict[str, object], name: str) -> int:
    location = record.get("location")
    value = location.get(name) if isinstance(location, dict) else None
    return value if isinstance(value, int) else 0


def parse_findings(stdout: str) -> list[Finding]:
    """Parse `ruff check --output-format json`. Syntax errors keep the code `invalid-syntax`."""
    try:
        records = json.loads(stdout)
    except json.JSONDecodeError as exc:
        raise RuffError(f"ruff did not print JSON: {exc}") from exc
    if not isinstance(records, list):
        raise RuffError("ruff printed JSON that is not a list of findings")
    findings: list[Finding] = []
    for record in records:
        if not isinstance(record, dict):
            continue
        filename = record.get("filename")
        code = record.get("code")
        message = record.get("message")
        findings.append(
            Finding(
                path=_relative(filename) if isinstance(filename, str) else "",
                code=code if isinstance(code, str) and code else SYNTAX_ERROR,
                row=_int_field(record, "row"),
                column=_int_field(record, "column"),
                message=message if isinstance(message, str) else "",
            )
        )
    return findings


def run_ruff() -> list[Finding]:
    """Findings of the project config with the baseline (and only the baseline) switched off."""
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            "check",
            "--exit-zero",
            "--no-cache",
            "--output-format",
            "json",
            "--config",
            "lint.per-file-ignores = {}",
            ".",
        ],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    if result.returncode != 0:
        raise RuffError(
            f"ruff exited with status {result.returncode}:\n{result.stderr.strip()}"
        )
    return parse_findings(result.stdout)


def group(findings: list[Finding]) -> Baseline:
    entries: Baseline = {}
    for finding in findings:
        entries.setdefault(finding.path, set()).add(finding.code)
    return entries


def render(entries: Baseline) -> str:
    lines = [*HEADER, "", TABLE]
    for path in sorted(entries):
        if GLOB_CHARS & set(path):
            # per-file-ignores keys are globs: such a path would match other files.
            raise RuffError(f"cannot baseline {path!r}: it contains glob characters")
        codes = ", ".join(json.dumps(code) for code in sorted(entries[path]))
        lines.append(f"{json.dumps(path)} = [{codes}]")
    return "\n".join(lines) + "\n"


def parse_baseline(text: str) -> Baseline:
    """Read a baseline rendered by `render`. Text only: no tomllib on Python 3.10."""
    entries: Baseline = {}
    for line in text.splitlines():
        match = ENTRY.match(line.strip())
        if match is None:
            continue
        path = json.loads(f'"{match.group(1)}"')
        codes = {code.strip().strip('"') for code in match.group(2).split(",")}
        entries[path] = {code for code in codes if code}
    return entries


def read_baseline() -> str:
    return BASELINE.read_text(encoding="utf-8") if BASELINE.exists() else ""


def pairs(entries: Baseline) -> set[tuple[str, str]]:
    return {(path, code) for path, codes in entries.items() for code in codes}


def _git(*args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["git", *args],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )


def renamed_paths(base_ref: str) -> dict[str, str]:
    """New path -> old path for files renamed since `base_ref`, relative to apps/backend."""
    diff = _git("diff", "--name-status", "-M", base_ref, "--", ".")
    renames: dict[str, str] = {}
    for line in diff.stdout.splitlines():
        parts = line.split("\t")
        if len(parts) == 3 and parts[0].startswith("R"):
            old, new = (part.removeprefix(REPO_PREFIX) for part in parts[1:])
            renames[new] = old
    return renames


def grown_entries(
    current: Baseline, old: Baseline, renames: dict[str, str]
) -> list[tuple[str, str]]:
    """File/code pairs in `current` that `old` did not list (a moved file keeps its entry)."""
    grown = []
    for path, code in pairs(current):
        if code not in old.get(renames.get(path, path), set()):
            grown.append((path, code))
    return sorted(grown)


def ruff_config(pyproject_text: str) -> str:
    """The [tool.ruff*] tables without comments or blank lines, for comparison."""
    kept: list[str] = []
    in_ruff = False
    for raw in pyproject_text.splitlines():
        line = re.sub(r"(^|\s)#.*$", "", raw).strip()
        if line.startswith("["):
            in_ruff = line.startswith(("[tool.ruff]", "[tool.ruff."))
        if in_ruff and line:
            kept.append(line)
    return "\n".join(kept)


def config_change_reason(base_ref: str) -> str | None:
    old = _git("show", f"{base_ref}:{REPO_PREFIX}pyproject.toml")
    if old.returncode != 0:
        return None
    if ruff_config(old.stdout) != ruff_config(PYPROJECT.read_text(encoding="utf-8")):
        return "changes the ruff config in pyproject.toml (rules or pin)"
    return None


def check_growth(base_ref: str, committed: Baseline) -> bool:
    """False when the committed baseline lists pairs the baseline at `base_ref` did not."""
    old = _git("show", f"{base_ref}:{REPO_PREFIX}{BASELINE.name}")
    if old.returncode != 0:
        print(f"ruff_baseline: {base_ref} has no {BASELINE.name}; growth not checked.")
        return True
    grown = grown_entries(
        committed, parse_baseline(old.stdout), renamed_paths(base_ref)
    )
    if not grown:
        return True
    reason = config_change_reason(base_ref)
    if reason is not None:
        print(
            f"\nruff_baseline: {len(grown)} file/code pair(s) added compared with "
            f"{base_ref}. Allowed because this change {reason}; reviewers, check them:"
        )
        for path, code in grown:
            print(f"  {path}: {code}")
        return True
    print(
        f"\nruff_baseline: {len(grown)} file/code pair(s) added compared with "
        f"{base_ref}. The baseline only shrinks; fix these instead:",
        file=sys.stderr,
    )
    for path, code in grown:
        print(f"  {path}: {code}", file=sys.stderr)
    return False


def check(findings: list[Finding], committed_text: str, base_ref: str | None) -> bool:
    current = group(findings)
    committed = parse_baseline(committed_text)
    ok = True

    added = pairs(current) - pairs(committed)
    if added:
        ok = False
        print(
            f"\n{len(added)} file/code pair(s) with findings the baseline does not list:\n",
            file=sys.stderr,
        )
        for finding in sorted(findings, key=lambda f: (f.path, f.row, f.column)):
            if (finding.path, finding.code) in added:
                print(f"  {finding.describe()}", file=sys.stderr)
        print(
            "\nFix them (`ruff check --fix` handles some); the baseline only holds "
            "findings that predate a rule. Do not run --update to accept them.",
            file=sys.stderr,
        )

    stale = sorted(pairs(committed) - pairs(current))
    if stale:
        ok = False
        print(
            f"\n{len(stale)} baseline entr(y/ies) no longer occur. Nice! Run "
            "`python scripts/ruff_baseline.py --update` and commit the smaller baseline:",
            file=sys.stderr,
        )
        for path, code in stale:
            print(f"  {path}: {code}", file=sys.stderr)

    if ok and render(current) != committed_text:
        ok = False
        print(
            f"\n{BASELINE.name} differs from the generated file (edited by hand?). "
            "Run `python scripts/ruff_baseline.py --update`.",
            file=sys.stderr,
        )

    if base_ref and not check_growth(base_ref, committed):
        ok = False
    return ok


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--update", action="store_true", help="rewrite the baseline")
    mode.add_argument(
        "--check", action="store_true", help="compare with the baseline (default)"
    )
    parser.add_argument(
        "--base-ref",
        help="fail if the baseline gained entries compared with this git ref",
    )
    args = parser.parse_args(argv)

    try:
        findings = run_ruff()
        syntax = [f for f in findings if f.code == SYNTAX_ERROR]
        if syntax:
            for finding in syntax:
                print(f"  {finding.describe()}", file=sys.stderr)
            raise RuffError("syntax errors cannot be baselined; fix them first")
        rendered = render(group(findings))
    except RuffError as exc:
        print(f"ruff_baseline: {exc}", file=sys.stderr)
        return 2

    committed_text = read_baseline()
    if args.update:
        BASELINE.write_text(rendered, encoding="utf-8", newline="\n")
        before = len(pairs(parse_baseline(committed_text)))
        after = len(pairs(group(findings)))
        print(
            f"ruff_baseline: wrote {after} file/code pair(s) to {BASELINE.name} (was {before})."
        )
        return 0

    print(
        f"ruff_baseline: {len(findings)} finding(s) in "
        f"{len(pairs(group(findings)))} file/code pair(s)."
    )
    if not check(findings, committed_text, args.base_ref):
        return 1
    print("ruff_baseline: baseline is up to date.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
